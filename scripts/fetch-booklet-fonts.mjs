// Matches the weights/styles previously requested from Google Fonts.
const FACES = [
  { weight: 400, style: 'normal', file: 'latin-400-normal' },
  { weight: 400, style: 'italic', file: 'latin-400-italic' },
  { weight: 600, style: 'normal', file: 'latin-600-normal' },
  { weight: 700, style: 'normal', file: 'latin-700-normal' },
  { weight: 700, style: 'italic', file: 'latin-700-italic' },
];

function fetchBuffer(url) {
  return new Promise((resolve, reject) => {
    const lib = url.startsWith('https') ? https : http;
    const req = lib.get(url, { headers: { 'User-Agent': 'polyphony-booklet-font-fetch/1' } }, (res) => {
      if (res.statusCode >= 300 && res.statusCode < 400 && res.headers.location) {
        fetchBuffer(res.headers.location).then(resolve, reject);
        return;
      }
      if (res.statusCode !== 200) {
        reject(new Error('HTTP ' + res.statusCode + ' for ' + url));
        res.resume();
        return;
      }
      const chunks = [];
      res.on('data', (c) => chunks.push(c));
      res.on('end', () => resolve(Buffer.concat(chunks)));
    });
    req.on('error', reject);
  });
}

async function tryDownload(slug, face) {
  // Prefer woff2 from fontsource fonts CDN
  const urls = [
    `https://cdn.jsdelivr.net/fontsource/fonts/${slug}@latest/${face.file}.woff2`,
    `https://cdn.jsdelivr.net/npm/@fontsource/${slug}/files/${slug}-${face.file}.woff2`,
  ];
  for (const url of urls) {
    try {
      const buf = await fetchBuffer(url);
      if (buf.length > 1000) return buf;
    } catch {
      /* try next */
    }
  }
  return null;
}

fs.mkdirSync(OUT, { recursive: true });
const cssParts = [
  '/* Auto-generated booklet body fonts — do not edit by hand.',
  '   Regenerated by scripts/fetch-booklet-fonts.mjs */',
  '',
];
const report = [];

for (const [family, slug] of Object.entries(FONTS)) {
  const dir = path.join(OUT, slug);
  fs.mkdirSync(dir, { recursive: true });
  let got = 0;
  for (const face of FACES) {
    const destName = `${face.file}.woff2`;
    const dest = path.join(dir, destName);
    let buf = null;
    if (fs.existsSync(dest) && fs.statSync(dest).size > 1000) {
      buf = fs.readFileSync(dest);
    } else {
      buf = await tryDownload(slug, face);
      if (buf) fs.writeFileSync(dest, buf);
    }
    if (!buf) {
      report.push(`MISS  ${family} ${face.file}`);
      continue;
    }
    got++;
    const urlPath = `/modules/liturgy-booklet/fonts/${slug}/${destName}`;
    cssParts.push(`@font-face {`);
    cssParts.push(`  font-family: '${family}';`);
    cssParts.push(`  font-style: ${face.style};`);
    cssParts.push(`  font-weight: ${face.weight};`);
    cssParts.push(`  font-display: block;`);
    cssParts.push(`  src: url('${urlPath}') format('woff2');`);
    cssParts.push(`}`);
    cssParts.push('');
  }
  report.push(`OK    ${family} (${slug}): ${got}/${FACES.length} faces`);
}

fs.writeFileSync(CSS_OUT, cssParts.join('\n'), 'utf8');
console.log(report.join('\n'));
